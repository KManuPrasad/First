package FirstPackage;

public class ElseIf {
	
	public static void main(String args[])
	{
	
	int a =34;
	int b = 33;
	
	if (a==b)
	{System.out.println("if statement");}
	
	else if (a==110)
	{
		System.out.println("else if");
	}
	else if (a==6)
	{
		System.out.println("2nd else if");
	}
	else
	{
		System.out.println("end");
	}
}
}
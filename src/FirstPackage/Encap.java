package FirstPackage;

public class Encap {
	private int number;
	private String name;
	private float percentage;
	
	public int getNumber() {//display or write
		return number;
	}
	public void setNumber(int number) {// set the value 
		this.number = number;
	}
	public String getName() {
		return name;
	}
	public void setName(String name) {
		this.name = name;
	}
	public float getPercentage() {
		return percentage;
	}
	public void setPercentage(float percentage) {
		this.percentage = percentage;
	}
	
	

}
